"""Exports one benchmark report to the website (crescent-docs).

    python3 bench/export_site.py reports/<stamp> "../New Crescent/crescent-docs"

Writes <site>/benchmark-data.js (window.CRESCENT_BENCH = {...}) and copies
results.csv to <site>/benchmark-results.csv for download.
"""
import json
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from aggregate import load  # noqa: E402


def main(report_dir, site_dir):
    report, site = Path(report_dir), Path(site_dir)
    env = {}
    for line in (report / "environment.txt").read_text().splitlines():
        # "key=value key2=value2" pairs; the first key owns the rest of the line
        # unless more key= tokens follow.
        parts = line.split(" ")
        key, current = None, []
        for part in parts:
            if "=" in part and not part.startswith("-"):
                if key:
                    env[key] = " ".join(current)
                key, _, first = part.partition("=")
                current = [first]
            else:
                current.append(part)
        if key:
            env[key] = " ".join(current)

    rows = load(report / "results.csv")
    for r in rows:
        if r["scenario"] == "idle":
            r["rss"] = r["rss_idle"]
        del r["rss_idle"]
    data = {"report": report.name, "environment": env, "results": rows}
    js = ("// Generated by benchmark/bench/export_site.py from reports/"
          + report.name + " — do not edit by hand.\n"
          + "window.CRESCENT_BENCH = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")
    (site / "benchmark-data.js").write_text(js)
    shutil.copyfile(report / "results.csv", site / "benchmark-results.csv")
    print(f"exported {len(rows)} rows from {report.name} to {site}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
